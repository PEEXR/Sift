    @Test
    fun embedText_againstAllFiveGoldenQueries_achievesCosineSimilarityAboveThreshold() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val modelStore = ModelStore(context)

        // Only run when real model files are installed on the device / emulator
        Assume.assumeTrue(
            "Model files are not installed on device; skipping instrumented integration test.",
            modelStore.isInstalled()
        )

        val engine = EmbeddingEngine(context, modelStore)

        try {
            runBlocking {
                for ((query, expectedEmb) in GOLDEN_EMBEDDINGS) {
                    val actualEmb = engine.embedText(query)

                    val similarity = cosineSimilarity(actualEmb, expectedEmb)
                    assertTrue(
                        "Query '$query' cosine similarity was $similarity (expected >= 0.999)",
                        similarity >= 0.999f
                    )
                }
            }
        } finally {
            engine.close()
        }
    }
